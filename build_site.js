// Builds the GitHub Pages / installable (PWA) version into docs/:
//   docs/index.html            the app (same code as the Claude artifact, with BUILD = 'pages')
//   docs/sw.js                 service worker: app opens without network; serves downloaded fonts
//   docs/manifest.webmanifest, docs/icons/*
//   docs/fonts/<id>/<id>.css   one stylesheet per family (woff2 only; Latin + Latin-ext, or CJK slices)
//   docs/fonts/<id>/files/*    the font files, docs/fonts/<id>/LICENSE
//   docs/fonts/packs.json      the three offline packs: file lists and sizes
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = __dirname, OUT = path.join(ROOT, 'docs'), FS = path.join(ROOT, 'node_modules/@fontsource');
const GF = new Function(fs.readFileSync(path.join(ROOT, 'src/fontdb.gen.js'), 'utf8') + ';return GF;')();
const idOf = n => n.toLowerCase().replace(/ /g, '-');
const PACKS = { latin: { name: '英文字体', files: [], bytes: 0, fams: 0 }, sc: { name: '简体中文字体', files: [], bytes: 0, fams: 0 }, cjk: { name: '繁体、日文、韩文字体', files: [], bytes: 0, fams: 0 } };
const KEEP = /^(latin|latin-ext|\d+)$/;           // drop cyrillic, greek, vietnamese slices
fs.rmSync(path.join(OUT, 'fonts'), { recursive: true, force: true });
const self = {}, report = [];
for (const f of GF) {
  const [name, , weights, hasIt, , script] = f, id = idOf(name), dir = path.join(FS, id);
  if (!fs.existsSync(dir)) { report.push('missing ' + name); continue; }
  const pack = script === '' ? 'latin' : script === 'sc' ? 'sc' : 'cjk';
  const od = path.join(OUT, 'fonts', id), of = path.join(od, 'files');
  fs.mkdirSync(of, { recursive: true });
  let css = '', bytes = 0, files = [];
  const got = { w: [], it: false };
  for (const it of hasIt ? [false, true] : [false]) for (const w of weights) {
    const cf = path.join(dir, w + (it ? '-italic' : '') + '.css');
    if (!fs.existsSync(cf)) { if (!it) report.push('no weight ' + name + ' ' + w); continue; }
    const src = fs.readFileSync(cf, 'utf8');
    for (const block of src.split(/(?=\/\* )/)) {
      const m = /^\/\* (.+?) \*\/\s*(@font-face\s*\{[\s\S]*?\})/.exec(block.trim());
      if (!m) continue;
      const tag = m[1].replace(id + '-', ''), sub = /^\[?(.+?)\]?-\d+-(normal|italic)$/.exec(tag);
      if (!sub || !KEEP.test(sub[1])) continue;
      const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(m[2]);
      if (!file) continue;
      const fp = path.join(dir, 'files', file[1]);
      if (!fs.existsSync(fp)) continue;
      fs.copyFileSync(fp, path.join(of, file[1]));
      const sz = fs.statSync(fp).size;
      bytes += sz; files.push('fonts/' + id + '/files/' + file[1]);
      css += m[2].replace(/src:[^;]+;/, "src: url(files/" + file[1] + ") format('woff2');").replace(/\n\s*/g, ' ') + '\n';
      if (it) got.it = true; else if (!got.w.includes(w)) got.w.push(w);
    }
  }
  if (!css) { report.push('nothing kept ' + name); fs.rmSync(od, { recursive: true, force: true }); continue; }
  fs.writeFileSync(path.join(od, id + '.css'), css);
  const lic = ['LICENSE', 'LICENSE.md', 'OFL.txt'].map(n => path.join(dir, n)).find(p => fs.existsSync(p));
  if (lic) fs.copyFileSync(lic, path.join(od, 'LICENSE'));
  const pj = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  files.push('fonts/' + id + '/' + id + '.css');
  bytes += css.length;
  PACKS[pack].files.push(...files); PACKS[pack].bytes += bytes; PACKS[pack].fams++;
  self[name] = { id, p: pack, l: pj.license || '' };
}
fs.writeFileSync(path.join(OUT, 'fonts', 'packs.json'), JSON.stringify(PACKS));
fs.writeFileSync(path.join(ROOT, 'src', 'selffonts.gen.js'), '/* Generated by build_site.js: fonts this site hosts itself, and the offline pack each belongs to. */\nconst SELF_FONTS = ' + JSON.stringify(self) + ';\nconst FONT_PACKS = ' + JSON.stringify(Object.fromEntries(Object.entries(PACKS).map(([k, v]) => [k, { name: v.name, bytes: v.bytes, n: v.files.length, fams: v.fams }]))) + ';\n');
for (const [k, v] of Object.entries(PACKS)) console.log(k, v.fams, 'families', v.files.length, 'files', (v.bytes / 1e6).toFixed(1) + ' MB');
if (report.length) console.log('notes:', report.length, report.slice(0, 30).join('; '));
